import {readFileSync} from 'node:fs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { scryptSync } from 'node:crypto';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';

test('prywatne API, logowanie, CSRF, wylogowanie i dane spoza katalogu publicznego',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'sygnal-http-'));
  const salt='temporary-test-salt',password='test-password-long-123';
  const port=4279,base=`http://127.0.0.1:${port}`,origin='https://sygnal.example';
  const child=spawn(process.execPath,['server.mjs'],{cwd:new URL('..',import.meta.url),env:{...process.env,DEV_MODE:'0',NODE_ENV:'production',PORT:String(port),APP_ORIGIN:origin,DATA_DIR:dir,APP_PASSWORD_HASH:salt+':'+scryptSync(password,salt,32).toString('hex'),WORKER_TOKEN:'test-only-worker-token-longer-than-32-chars'},stdio:['ignore','pipe','pipe']});
  t.after(async()=>{child.kill('SIGTERM');if(child.exitCode===null)await once(child,'exit');await rm(dir,{recursive:true,force:true});});
  await Promise.race([once(child.stdout,'data'),once(child,'exit').then(()=>{throw new Error('Serwer nie wystartował');})]);
  const request=(path,options={})=>fetch(base+path,options);
  assert.equal((await request('/api/dashboard')).status,401);
  assert.equal((await request('/api/price-history?id=AKCJA-001&period=1d')).status,401);
  assert.equal((await request('/api/deployment/status')).status,401);
  assert.equal((await request('/api/deployment/deploy',{method:'POST',headers:{Origin:origin},body:JSON.stringify({id:'fake'})})).status,401);
  assert.equal((await request('/catalog.json')).status,404);
  assert.equal((await request('/.env')).status,404);
  assert.equal((await request('/manifest.webmanifest')).status,200);
  assert.equal((await request('/api/login',{method:'POST',headers:{Origin:'https://evil.example'},body:JSON.stringify({password})})).status,403);
  const login=await request('/api/login',{method:'POST',headers:{Origin:origin},body:JSON.stringify({password})});
  assert.equal(login.status,200);assert.match(login.headers.get('set-cookie'),/HttpOnly; SameSite=Strict.*Secure/);
  const cookie=login.headers.get('set-cookie').split(';')[0];
  assert.equal((await request('/api/price-history?id=AKCJA-001&period=evil',{headers:{Cookie:cookie}})).status,400);
  assert.equal((await request('/api/price-history?id=unknown&period=1d',{headers:{Cookie:cookie}})).status,404);
  assert.equal((await request('/price-chart.js')).status,200);
  assert.equal((await request('/api/deployment/prepare',{method:'POST',headers:{Cookie:cookie,Origin:'https://evil.example'},body:'{}'})).status,403);
  const deployment=await request('/api/deployment/status',{headers:{Cookie:cookie}});assert.equal(deployment.status,200);assert.equal((await deployment.json()).enabled,false);
  const dash=await request('/api/dashboard',{headers:{Cookie:cookie}});assert.equal(dash.status,200);assert.equal((await dash.json()).instruments.length,JSON.parse(readFileSync(new URL('../catalog.json',import.meta.url),'utf8')).items.length);
  assert.equal((await postSettings({pricesFrequency:'weekly'})).status,400);
  async function postSettings(b){return request('/api/settings',{method:'POST',headers:{Cookie:cookie,Origin:origin},body:JSON.stringify(b)});}
  assert.equal((await postSettings({pricesFrequency:'twice_weekly',publicationsFrequency:'twice_daily',scope:'bought',reminderDays:3,reminderHour:10})).status,200);
  const prefs=await (await request('/api/dashboard',{headers:{Cookie:cookie}})).json();
  assert.equal(prefs.settings.publicationsFrequency,'twice_daily');
  assert.equal(prefs.settings.reminderDays,3);
  const buy={instrument_id:'AKCJA-001',quantity:0.5,price:120,currency:'USD',purchased_on:'2026-11-02'};
  const post=(path,b)=>request(path,{method:'POST',headers:{Cookie:cookie,Origin:origin},body:JSON.stringify(b)});
  assert.equal((await post('/api/purchase',{...buy,quantity:-1})).status,400);
  assert.equal((await post('/api/purchase',{...buy,purchased_on:'2026-02-31'})).status,400);
  assert.equal((await post('/api/purchase',buy)).status,200);
  assert.equal((await post('/api/purchase',{...buy,quantity:1.25,price:130})).status,200);
  let portfolio=await (await request('/api/dashboard',{headers:{Cookie:cookie}})).json();
  assert.equal(portfolio.purchases.length,2);
  assert.equal(portfolio.purchases.reduce((n,p)=>n+p.quantity,0),1.75);
  assert.equal(portfolio.instruments.find(i=>i.id==='AKCJA-001').watched,0);
  assert.equal(portfolio.quotes.length,0);
  await post('/api/purchase-delete',{id:portfolio.purchases[0].id});
  portfolio=await (await request('/api/dashboard',{headers:{Cookie:cookie}})).json();
  assert.equal(portfolio.purchases.length,1);
  assert.equal((await request('/api/watch',{method:'POST',headers:{Cookie:cookie,Origin:'https://evil.example'},body:'{}'})).status,403);
  assert.equal((await request('/api/worker/claim',{method:'POST',body:'{}'})).status,401);
  await request('/api/logout',{method:'POST',headers:{Cookie:cookie,Origin:origin},body:'{}'});
  assert.equal((await request('/api/dashboard',{headers:{Cookie:cookie}})).status,401);
});
